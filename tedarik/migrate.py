"""Şema yönetimi: Resource tanımlarından tablo, dizin ve tetikleyici; sürümlü göç kaydı.

İki katman vardır:
1. **Bildirimsel eşitleme** (her açılışta, kilit altında): eksik tablo açılır, yeni ve boş bırakılabilir alan
   eklenir, yabancı anahtar dizinleri ve değişmez tablo tetikleyicileri kurulur. Zorunlu veya tekil yeni alan
   kendiliğinden eklenmez; açık göç ister.
2. **Sürümlü göçler** (`MIGRATIONS`): veri dönüştüren veya ad değiştiren adımlar. Her biri bir kez, kendi
   işleminde çalışır ve `tdr_schema_migrations` tablosuna yazılır. Sıra numarası değişmez; uygulanmış bir
   göç düzenlenmez, yenisi eklenir.

Kimlik tabloları (K-013) KS GRC şemasıyla aynı adla ve aynı TEXT tipleriyle burada açılır; böylece KS GRC
`identity.py` iki motorda değiştirilmeden çalışır.
"""
from .db import FOLD_FROM, FOLD_TO, utcnow
from .schema import RESOURCES

IMMUTABLE_MESSAGE = "Bu kayıt değiştirilemez ve silinemez (denetim kanıtı)"

# (sıra, açıklama, işlev(db)). İlk sürümde veri dönüşümü yok; tablo yapısı bildirimsel eşitlemeden gelir.
MIGRATIONS = []


def _identity_ddl(dialect):
    ident = ("id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if dialect == "postgres"
             else "id INTEGER PRIMARY KEY AUTOINCREMENT")
    integer = "BIGINT" if dialect == "postgres" else "INTEGER"
    return [
        # control@7720f4b app.py + identity.setup ile aynı sütunlar (kimlik tabloları ortak: K-013)
        f"""CREATE TABLE IF NOT EXISTS users ({ident}, username TEXT NOT NULL UNIQUE, email TEXT UNIQUE,
            display_name TEXT NOT NULL, is_active INTEGER NOT NULL DEFAULT 1 CHECK(is_active IN (0,1)),
            created_at TEXT NOT NULL, updated_at TEXT, password_hash TEXT,
            must_change_password INTEGER NOT NULL DEFAULT 1, last_login_at TEXT)""",
        f"""CREATE TABLE IF NOT EXISTS auth_sessions (token_hash TEXT PRIMARY KEY,
            user_id {integer} NOT NULL REFERENCES users(id) ON DELETE CASCADE, expires_at TEXT NOT NULL,
            created_at TEXT NOT NULL, auth_scope TEXT NOT NULL DEFAULT 'local', app_role TEXT)""",
        f"""CREATE TABLE IF NOT EXISTS entra_subjects (tenant TEXT NOT NULL, oid TEXT NOT NULL,
            user_id {integer} UNIQUE NOT NULL REFERENCES users(id), PRIMARY KEY(tenant, oid))""",
        "CREATE INDEX IF NOT EXISTS auth_sessions_expiry ON auth_sessions(expires_at)",
        "CREATE INDEX IF NOT EXISTS auth_sessions_user ON auth_sessions(user_id)",
    ]


def _immutable(db, table):
    if db.dialect == "postgres":
        db.execute(f"""CREATE OR REPLACE TRIGGER {table}_immutable BEFORE UPDATE OR DELETE ON {table}
            FOR EACH ROW EXECUTE FUNCTION tdr_immutable()""")
        return
    for op in ("UPDATE", "DELETE"):
        db.execute(f"""CREATE TRIGGER IF NOT EXISTS {table}_immutable_{op.lower()} BEFORE {op} ON {table}
            BEGIN SELECT RAISE(ABORT, '{IMMUTABLE_MESSAGE}'); END""")


def _ordered(resources):
    """Başvurulan tablo önce açılır (PostgreSQL ileri başvuruya izin vermez)."""
    by_table = {r.table: r for r in resources}
    done, result = set(), []

    def visit(res, path=()):
        if res.table in done:
            return
        if res.table in path:
            raise RuntimeError("Döngüsel tablo başvurusu: " + " -> ".join(path))
        for column in res.columns.values():
            target = by_table.get(column.ref)
            if target is not None and target is not res:
                visit(target, path + (res.table,))
        done.add(res.table)
        result.append(res)
    for res in resources:
        visit(res)
    return result


def sync(database, modules):
    """Etkin modüllerin şemasını kurar ve bekleyen göçleri uygular. Birden çok süreç aynı anda açılabilir."""
    with database.connect() as db:
        if db.dialect == "sqlite":
            db.execute("PRAGMA journal_mode=WAL")
        db.lock("schema")
        if db.dialect == "postgres":
            db.execute(f"""CREATE OR REPLACE FUNCTION tdr_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
                BEGIN RAISE EXCEPTION '{IMMUTABLE_MESSAGE}' USING ERRCODE = '23000'; END $$""")
        if db.dialect == "postgres":   # yerel ayardan bağımsız: önce harf çevirisi, sonra ASCII küçültme
            db.execute(f"""CREATE OR REPLACE FUNCTION tdr_fold(value TEXT) RETURNS TEXT LANGUAGE sql IMMUTABLE
                PARALLEL SAFE AS $$ SELECT lower(translate(value, '{FOLD_FROM}', '{FOLD_TO}')) $$""")
        for statement in _identity_ddl(db.dialect):
            db.execute(statement)
        db.execute("CREATE TABLE IF NOT EXISTS tdr_schema_migrations (version INTEGER PRIMARY KEY, "
                   "description TEXT NOT NULL, applied_at TEXT NOT NULL)")
        active = _ordered([r for r in RESOURCES.values() if r.module in modules])
        for res in active:
            db.execute(res.ddl(db.dialect))
        for res in active:
            have = db.columns(res.table)
            for name, column in res.columns.items():
                if name in have:
                    continue
                if column.required or column.unique:
                    raise RuntimeError(f"{res.table}.{name} için açık göç gerekli (zorunlu veya tekil yeni alan)")
                db.execute(f"ALTER TABLE {res.table} ADD COLUMN {name} {column.sql(db.dialect)}")
            for cols in res.index_columns():
                db.execute(f"CREATE INDEX IF NOT EXISTS {res.table}_{'_'.join(cols)}_idx "
                           f"ON {res.table} ({', '.join(cols)})")
            if res.immutable:
                _immutable(db, res.table)
        done = {r["version"] for r in db.execute("SELECT version FROM tdr_schema_migrations").fetchall()}
        for version, description, step in MIGRATIONS:
            if version not in done:
                step(db)
                db.execute("INSERT INTO tdr_schema_migrations (version, description, applied_at) VALUES (?,?,?)",
                           (version, description, utcnow()))
    database.schema_changed()
