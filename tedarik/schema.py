"""Bildirimsel kaynak kaydı: KS GRC'deki TABLES sözlüğünün modüler karşılığı.

Her kaynak bir tabloya (tdr_ önekli) ve /api/tdr/<ad> uç noktasına karşılık gelir.
Yeni bir alan eklemek için yalnızca ilgili Resource tanımına satır eklenir; tablo açılışta genişler.

Alan tanımı KS GRC'deki gibi SQL benzeri bir metindir ve mantıksal tip taşır:
  TEXT · INTEGER · REAL · DECIMAL (para, 2 basamak) · DATE (YYYY-AA-GG) · TIMESTAMP (UTC, saat dilimli ISO 8601)
  + NOT NULL · DEFAULT <değer> · UNIQUE · REFERENCES <tablo>(id) [ON DELETE CASCADE]
Motor karşılıkları `Field.sql()` içindedir: PostgreSQL'de yerel tipler (DATE, TIMESTAMPTZ, NUMERIC, BIGINT),
SQLite'ta KS GRC ile aynı TEXT/INTEGER/REAL. Doğrulama ve normalleştirme motor bağımsızdır (crud.py).
"""
import re

PREFIX = "tdr_"
RESOURCES = {}
AUTO = {"created_at", "updated_at"}
KINDS = ("TEXT", "INTEGER", "REAL", "DECIMAL", "DATE", "TIMESTAMP")
_DEFINITION = re.compile(
    r"^(?P<kind>TEXT|INTEGER|REAL|DECIMAL|DATE|TIMESTAMP)"
    r"(?P<not_null> NOT NULL)?"
    r"(?: DEFAULT (?P<default>'[^']*'|-?\d+(?:\.\d+)?))?"
    r"(?P<unique> UNIQUE)?"
    r"(?: REFERENCES (?P<ref>[a-z_]+)\(id\)(?P<cascade> ON DELETE CASCADE)?)?$")
PG_TYPES = {"TEXT": "TEXT", "INTEGER": "BIGINT", "REAL": "DOUBLE PRECISION", "DECIMAL": "NUMERIC(18,2)",
            "DATE": "DATE", "TIMESTAMP": "TIMESTAMPTZ"}
SQLITE_TYPES = {"TEXT": "TEXT", "INTEGER": "INTEGER", "REAL": "REAL", "DECIMAL": "REAL",
                "DATE": "TEXT", "TIMESTAMP": "TEXT"}


class Field:
    def __init__(self, name, definition):
        match = _DEFINITION.match(definition)
        if not match:
            raise ValueError(f"Geçersiz alan tanımı: {name} {definition}")
        self.name, self.definition = name, definition
        self.kind = match["kind"]
        self.not_null = bool(match["not_null"])
        self.default = match["default"]
        self.unique = bool(match["unique"])
        self.ref = match["ref"]
        self.cascade = bool(match["cascade"])

    @property
    def required(self):
        return self.not_null and self.default is None

    def sql(self, dialect):
        types = PG_TYPES if dialect == "postgres" else SQLITE_TYPES
        parts = [types[self.kind]]
        if self.not_null:
            parts.append("NOT NULL")
        if self.default is not None:
            parts.append("DEFAULT " + self.default)
        if self.unique:
            parts.append("UNIQUE")
        if self.ref:
            parts.append(f"REFERENCES {self.ref}(id)" + (" ON DELETE CASCADE" if self.cascade else ""))
        return " ".join(parts)


def fk(resource, required=True, cascade=False):
    sql = "INTEGER" + (" NOT NULL" if required else "") + f" REFERENCES {PREFIX}{resource}(id)"
    return sql + (" ON DELETE CASCADE" if cascade else "")


class Resource:
    def __init__(self, name, label, fields, *, module, enums=None, unique=(), search=("code", "name"),
                 write="manage", api=("list", "get", "create", "update"), readonly=(), filters=None,
                 read_roles=None, machine="", immutable=False, indexes=()):
        self.name, self.label, self.fields, self.module = name, label, fields, module
        self.table = PREFIX + name
        self.columns = {f: Field(f, d) for f, d in fields.items()}
        self.enums = enums or {}
        self.unique = unique
        self.search = tuple(f for f in search if f in fields)
        self.write = write              # yazma için gereken en düşük seviye: write | manage | admin
        self.api = api                  # otomatik açılan uç noktalar
        self.readonly = set(readonly) | AUTO   # yalnızca sunucunun yazdığı alanlar
        self.filters = filters or {}    # ek liste filtreleri: ad -> SQL parçası (tek parametre)
        self.read_roles = read_roles    # None: tüm roller okur
        self.machine = machine          # MCP anahtarının erişimi: "", "r" veya "rw"
        self.immutable = immutable      # True: satır eklendikten sonra değiştirilemez, silinemez (tetikleyici)
        self.indexes = tuple(indexes)   # ek dizinler: sütun demetleri; yabancı anahtarlar kendiliğinden
        self.before_save = None         # kanca: (db, data, mevcut_kayıt, principal)
        self.required = [f for f, c in self.columns.items() if c.required and f not in self.readonly]
        RESOURCES[name] = self

    def ddl(self, dialect="sqlite"):
        ident = ("id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if dialect == "postgres"
                 else "id INTEGER PRIMARY KEY AUTOINCREMENT")
        cols = ", ".join(f"{f} {c.sql(dialect)}" for f, c in self.columns.items())
        uniq = "".join(f", UNIQUE({', '.join(u)})" for u in self.unique)
        return f"CREATE TABLE IF NOT EXISTS {self.table} ({ident}, {cols}{uniq})"

    def index_columns(self):
        """Yabancı anahtar sütunları (PostgreSQL bunları kendiliğinden dizinlemez) ve ek dizinler."""
        found = [(f,) for f, c in self.columns.items() if c.ref and not c.unique]
        found += [tuple(i) for i in self.indexes]
        leading = {u[0] for u in self.unique}
        return [cols for cols in dict.fromkeys(found) if not (len(cols) == 1 and cols[0] in leading)]
